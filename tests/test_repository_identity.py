from __future__ import annotations

import json
import subprocess
import uuid
from pathlib import Path

import pytest

from pcae.core.paths import HarnessPath
from pcae.core.repository_identity import (
    REPOSITORY_IDENTITY_RELATIVE_PATH,
    RepositoryIdentityMalformedError,
    RepositoryIdentitySymlinkError,
    ensure_repository_identity,
    read_repository_identity,
)


def _root(tmp_path: Path) -> HarnessPath:
    return HarnessPath(tmp_path)


def _identity_path(tmp_path: Path) -> Path:
    return tmp_path / REPOSITORY_IDENTITY_RELATIVE_PATH


def test_read_missing_identity_returns_none(tmp_path: Path) -> None:
    assert read_repository_identity(_root(tmp_path)) is None


def test_ensure_creates_valid_identity(tmp_path: Path) -> None:
    identity = ensure_repository_identity(_root(tmp_path))

    assert identity.schema_version == 1
    parsed = uuid.UUID(identity.repository_instance_id)
    assert parsed.version == 4
    assert _identity_path(tmp_path).exists()

    on_disk = json.loads(_identity_path(tmp_path).read_text(encoding="utf-8"))
    assert on_disk == identity.to_dict()


def test_ensure_is_idempotent(tmp_path: Path) -> None:
    first = ensure_repository_identity(_root(tmp_path))
    second = ensure_repository_identity(_root(tmp_path))

    assert first == second
    assert read_repository_identity(_root(tmp_path)) == first


def test_missing_and_malformed_are_distinct_outcomes(tmp_path: Path) -> None:
    path = _identity_path(tmp_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("not json", encoding="utf-8")

    with pytest.raises(RepositoryIdentityMalformedError):
        read_repository_identity(_root(tmp_path))

    # Malformed is never silently auto-regenerated by ensure().
    with pytest.raises(RepositoryIdentityMalformedError):
        ensure_repository_identity(_root(tmp_path))
    assert path.read_text(encoding="utf-8") == "not json"


